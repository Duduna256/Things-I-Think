// Builds supabase/seed.sql from src/lib/data/seed-data.json (the same sample data demo mode uses).
// Run: node scripts/generate-seed.mjs   (then paste supabase/seed.sql into the Supabase SQL editor)
import { readFileSync, writeFileSync } from "node:fs";

const seed = JSON.parse(readFileSync(new URL("../src/lib/data/seed-data.json", import.meta.url), "utf8"));
const q = v => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a, type) => `'{${a.map(x => (type === "text" ? `"${x}"` : x)).join(",")}}'::${type}[]`;
// Stable ids so re-running the seed updates rows instead of duplicating them.
const id = key => `extensions.uuid_generate_v5('6ba7b811-9dad-11d1-80b4-00c04fd430c8'::uuid, ${q(key)})`;
const upsert = (table, cols, rows, conflict, update) =>
  `insert into public.${table} (${cols.join(", ")}) values\n${rows.map(r => `  (${r.join(", ")})`).join(",\n")}\non conflict (${conflict}) do ${
    update.length ? `update set ${update.map(c => `${c} = excluded.${c}`).join(", ")}` : "nothing"
  };`;

const out = ["-- Sample data. Generated by scripts/generate-seed.mjs. Safe to re-run.", "begin;"];
out.push(upsert("categories", ["id", "name", "icon", "is_new", "sort"],
  seed.categories.map(c => [q(c.id), q(c.name), q(c.icon), c.isNew, c.sort]), "id", ["name", "icon", "is_new", "sort"]));
out.push(upsert("areas", ["id", "name", "region", "sort"],
  seed.areas.map(a => [q(a.id), q(a.name), q(a.region), a.sort]), "id", ["name", "region", "sort"]));

const bizCols = ["id", "slug", "name", "category_id", "area_id", "blurb", "visit_mode", "opens_at", "closes_at", "closed_days",
  "home_visit_fee", "accepts_cash", "skip_professional", "cover_word", "palette", "status", "is_featured", "is_new", "rating_avg", "rating_count", "sort"];
out.push(upsert("businesses", bizCols, seed.businesses.map(b => [
  id("biz:" + b.slug), q(b.slug), q(b.name), q(b.categoryId), q(b.areaId), q(b.blurb), q(b.visitMode), q(b.opensAt), q(b.closesAt),
  arr(b.closedDays, "smallint"), b.homeVisitFee, b.acceptsCash, b.skipProfessional, q(b.coverWord), arr(b.palette, "text"),
  "'published'", b.isFeatured, b.isNew, b.ratingAvg, b.ratingCount, b.sort,
]), "slug", bizCols.filter(c => !["id", "slug", "status"].includes(c))));

const svcCols = ["id", "business_id", "group_name", "name", "description", "duration_min", "duration_label", "price", "latest_start", "sort"];
out.push(upsert("services", svcCols, seed.businesses.flatMap(b => b.services.map(s => [
  id(`svc:${b.slug}:${s.key}`), id("biz:" + b.slug), q(s.groupName), q(s.name), q(s.description), s.durationMin, q(s.durationLabel), s.price, q(s.latestStart), s.sort,
])), "id", svcCols.slice(2)));

// A sample rating stands for 20 earlier reviews (as in demo.ts and migration 8), so a real review
// nudges it. Re-running leaves ratings alone: by then real reviews may have moved them.
const SAMPLE_STAFF_REVIEWS = 20;
const staffCols = ["id", "business_id", "name", "role", "rating", "rating_count", "rating_sum", "sort"];
out.push(upsert("staff", staffCols, seed.businesses.flatMap(b => b.staff.map(st => [
  id(`staff:${b.slug}:${st.sort}`), id("biz:" + b.slug), q(st.name), q(st.role), st.rating,
  st.rating > 0 ? SAMPLE_STAFF_REVIEWS : 0, st.rating > 0 ? +(st.rating * SAMPLE_STAFF_REVIEWS).toFixed(1) : 0, st.sort,
])), "id", ["name", "role", "sort"]));

// Sample reviews don't touch the rating counters (the seed already sets them).
out.push("alter table public.reviews disable trigger reviews_rating;");
out.push(upsert("reviews", ["id", "business_id", "rating", "title", "body", "author_name", "author_area", "is_sample"],
  seed.reviews.map(r => [id(`review:${r.businessSlug}:${r.authorName}`), id("biz:" + r.businessSlug), r.rating, q(r.title), q(r.body), q(r.authorName), q(r.authorArea), "true"]),
  "id", []));
out.push("alter table public.reviews enable trigger reviews_rating;", "commit;");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log("wrote supabase/seed.sql");
